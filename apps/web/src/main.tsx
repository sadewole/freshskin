import { StrictMode } from 'react';
import { createRoot } from 'react-dom/client';
import { MotionConfig } from 'motion/react';
import { registerSW } from 'virtual:pwa-register';
import { App } from './App';
import { SessionProvider } from './session/SessionProvider';
import './styles.css';

const container = document.getElementById('root');
if (container === null) throw new Error('#root is missing from index.html');

createRoot(container).render(
  <StrictMode>
    {/*
      reducedMotion="user" disables Motion transforms under
      prefers-reduced-motion, matching the CSS gate in tokens.css.
    */}
    <MotionConfig reducedMotion="user">
      <SessionProvider>
        <App />
      </SessionProvider>
    </MotionConfig>
  </StrictMode>,
);

/**
 * The service worker precaches the shell and never caches `/api` (see vite.config.ts), so the
 * app opens offline with "could not reach FreshSkin" rather than serving stale user data.
 * `registerSW` is generated by vite-plugin-pwa; it does not inject inline script, which keeps
 * the server's `script-src 'self'` CSP intact.
 */
registerSW({ immediate: false });
